    print("=== Part 1: closed-form check for W(r,1), W(r,2), r=0..8 ===")
    all_ok1 = True
    for r in range(0, 9):
        w1 = W(r, 1)
        w1_formula = 2 * math.factorial(r) * (r + 1) ** 2
        w2 = W(r, 2)
        w2_formula = math.factorial(r) * (r + 1) * (r + 2) * (2 * r + 3)
        ok1 = (w1 == w1_formula)
        ok2 = (w2 == w2_formula)
        all_ok1 = all_ok1 and ok1 and ok2
        print(f"r={r:>2}  W(r,1)={str(w1):>12} formula={w1_formula:>12} match={ok1}   "
              f"W(r,2)={str(w2):>14} formula={w2_formula:>14} match={ok2}")
